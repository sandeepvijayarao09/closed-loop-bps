"""Confound control: is the GRUs' closed-loop loss simulator mismatch or distribution shift?

The real-trained GRUs lose R^2 on simulated spikes (0.85 -> ~0.5) while the KF gains
(encoder_fidelity.json): the simulator favours linear decoders. Here every decoder is instead
trained on *simulated* spikes, generated by the encoding model from the real MC_Maze training
velocities (open loop, true labels, same trials, same hyperparameters), and then run closed loop.

  - If sim-trained GRUs do well in closed loop, the real-trained GRUs' loss was simulator mismatch.
  - If they still fail, the loss is distribution shift: trained on MC_Maze-style reaches, run on
    Webgrid-style continuous control, even when the neurons are exactly the model's.

Writes results/sim_trained.json, artifacts/decoders_sim.pkl.
"""
import os

os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("VECLIB_MAXIMUM_THREADS", "1")

import sys  # noqa: E402
from dataclasses import replace  # noqa: E402
from pathlib import Path  # noqa: E402

import numpy as np  # noqa: E402
import torch  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cbps import data  # noqa: E402
from cbps.decoders import KalmanVelocity, Wiener  # noqa: E402
from cbps.encoding import ENC_LAGS  # noqa: E402
from cbps.experiment import evaluate, pool, tune  # noqa: E402
from cbps.io import load_json, load_pickle, save_json, save_pickle  # noqa: E402
from cbps.metrics import r2  # noqa: E402
from cbps.train_gru import train_gru  # noqa: E402
from cbps.webgrid import TaskConfig, UserModel  # noqa: E402

KF_LEADS = (0, 2, 4, 5, 6, 8)
CAL_SEEDS = list(range(1000, 1006))
EVAL_SEEDS = list(range(0, 20))


def main():
    torch.set_num_threads(4)
    enc = load_pickle("encoder.pkl")
    off = load_json("offline.json")["decoders"]
    um = load_json("user_model.json")
    user = UserModel(vmax=um["vmax"], tau=um["tau"], tau_m=um["tau_m"])
    full = data.load(data.DECODE_LAG)
    itr, iva, ite = data.split_indices(full)
    Vs_enc = data.velocity_stack(ENC_LAGS)
    Vs_kf = data.velocity_stack(KF_LEADS)
    rng = np.random.default_rng(2024)
    Xs = enc.simulate_from_stack(Vs_enc, rng)  # simulated spikes for every trial, real kinematics
    V = full.V
    E = data.EVAL_START

    decs = {"KF": KalmanVelocity.fit(Xs[itr], V[itr]),
            "KF-lag": KalmanVelocity.fit_lagged(Xs[itr], Vs_kf[itr], KF_LEADS, data.DECODE_LAG),
            "Wiener": Wiener.fit(Xs[itr], V[itr], off["Wiener"]["n_hist"], off["Wiener"]["alpha"])}
    for h in (16, 64):
        decs[f"GRU-{h}"] = train_gru(Xs[itr], V[itr], Xs[iva], V[iva], hidden=h, seed=0)[0]
    real_te = full.subset(ite)
    out = {"note": __doc__.strip().splitlines()[0], "decoders": {}}
    for n, d in decs.items():
        out["decoders"][n] = {"sim_test_r2": r2(V[ite][:, E:], d.predict(Xs[ite])[:, E:]),
                              "real_test_r2": r2(real_te.V[:, E:], d.predict(real_te.X)[:, E:]),
                              "n_params": int(d.n_params)}
        print(n, out["decoders"][n])
    save_pickle("decoders_sim.pkl", decs)

    click = TaskConfig(mode="click", seconds=120.0)
    names = list(decs) + ["Oracle"]
    with pool(decs, enc) as p:
        tuned = tune(p, names, replace(click, seconds=60.0), user, CAL_SEEDS)
        res = evaluate(p, names, click, user, EVAL_SEEDS, {n: tuned[n][0] for n in names})
    for n in names:
        res[n].pop("per_session_bps")
        out["decoders"].setdefault(n, {})["closed_loop_click"] = res[n]
        print(f"  {n:8s} gain {res[n]['gain']:<5} BPS {res[n]['bps_mean']:.2f} "
              f"[{res[n]['bps_ci95'][0]:.2f}, {res[n]['bps_ci95'][1]:.2f}]")
    save_json("sim_trained.json", out)


if __name__ == "__main__":
    main()
