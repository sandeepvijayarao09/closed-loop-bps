"""Fit the simulator: encoding model (spikes | velocity) and simulated-user policy, on train trials.

Also measures simulator fidelity: every offline decoder is scored on real test
spikes and on simulated spikes generated from the same real test velocities.
If the simulator were perfect the two R^2 columns would match.

Writes artifacts/encoder.pkl, results/user_model.json, results/encoder_fidelity.json.
Usage: python scripts/03_fit_encoder.py
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cbps import BIN_S, data  # noqa: E402
from cbps.encoding import ENC_LAGS, bits_per_spike, fit_encoding_model, stacked_features  # noqa: E402
from cbps.io import load_pickle, save_json, save_pickle  # noqa: E402
from cbps.metrics import r2  # noqa: E402
from cbps.webgrid import fit_reach_policy  # noqa: E402

E = data.EVAL_START


def fit_user(tr):
    """User reach policy fit to the mean speed profile of real straight reaches (train split)."""
    m = tr.n_barriers == 0
    on = data.PRE_BINS
    prof = np.linalg.norm(tr.V[m], axis=-1)[:, on:on + 40].mean(0)
    vmax, tau, tm, rmse, sim = fit_reach_policy(tr.P[m][:, on], tr.P[m][:, -1], prof)
    return {"vmax": vmax, "tau": tau, "tau_m": tm, "train_rmse_mm_s": rmse, "real_profile": prof,
            "sim_profile": sim, "n_straight_reaches": int(m.sum()),
            "fit": "least squares on mean speed profile, 0-800 ms after onset, train split straight reaches"}


def main():
    full = data.load(data.DECODE_LAG)
    Vs = data.velocity_stack(ENC_LAGS)
    itr, iva, ite = data.split_indices(full)
    tr, te = full.subset(itr), full.subset(ite)
    enc = fit_encoding_model(tr.X, Vs[itr])
    save_pickle("encoder.pkl", enc)

    # Held-out encoding quality (test split).
    Y = te.X.reshape(-1, te.X.shape[-1])
    lam = np.exp(enc.log_rate(Vs[ite])).reshape(Y.shape)
    lam0 = np.broadcast_to(tr.X.reshape(-1, Y.shape[1]).mean(0), Y.shape)
    enc_bps = bits_per_spike(Y, lam, lam0)

    user = fit_user(data.load(0).subset(itr))
    save_json("user_model.json", user)
    print("user", {k: v for k, v in user.items() if "profile" not in k})

    decs = load_pickle("decoders.pkl")
    rng = np.random.default_rng(123)
    Xs = enc.simulate_from_stack(Vs[ite], rng, noise_scale=1.0)
    rows = {}
    te0_V = data.load(0).subset(ite).V  # target of the lag-0 ablations
    for name, d in decs.items():
        tv = te0_V if name.endswith("lag0") else te.V
        rows[name] = {"real_test_r2": r2(tv[:, E:], d.predict(te.X)[:, E:]),
                      "sim_test_r2": r2(tv[:, E:], d.predict(Xs)[:, E:])}
        print(name, rows[name])
    sr, ss = te.X[:, E:].reshape(-1, Y.shape[1]), Xs[:, E:].reshape(-1, Y.shape[1])
    save_json("encoder_fidelity.json", {
        "encoding_model": {"enc_lags_bins": list(ENC_LAGS), "test_bits_per_spike": enc_bps,
                           "n_params": int(enc.B.size + enc.C.size + enc.phi.size + enc.sigma_priv.size),
                           **enc.info},
        "rates_hz": {"real_test": float(sr.mean() / BIN_S), "sim_test": float(ss.mean() / BIN_S)},
        "fano_20ms_median": {"real_test": float(np.median(sr.var(0) / np.maximum(sr.mean(0), 1e-9))),
                             "sim_test": float(np.median(ss.var(0) / np.maximum(ss.mean(0), 1e-9)))},
        "decoders_real_vs_sim_r2": rows,
        "note": "Decoders trained on real train trials. sim_test_r2 uses spikes generated by the encoding "
                "model from the real test-trial velocities (noise_scale=1). Gap = simulator mismatch."})


if __name__ == "__main__":
    main()
